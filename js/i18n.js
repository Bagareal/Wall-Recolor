/** Language to start with: saved choice, else the browser language, else English. */
export function initialLang(saved, navLang) {
  if (LANGS.includes(saved)) return saved;
  const p = String(navLang || '').slice(0, 2).toLowerCase();
  return LANGS.includes(p) ? p : 'en';
}

/** Translate key k in language lang, replacing {x} placeholders from v. Unknown keys return the key itself. */
export function translate(lang, k, v) {
  let s = (I18N[lang] && I18N[lang][k]) || I18N.en[k] || k;
  if (v) for (const x in v) s = s.split('{' + x + '}').join(v[x]);
  return s;
}
